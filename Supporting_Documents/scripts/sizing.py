def block(name):
    n = re.sub(r"[^0-9]", "", name)
    if name.startswith(("Q§", "Mc", "Rnull", "Cc")) or name in ("R1", "R2", "R3", "R4", "R5", "R6", "R7"):
        return "Voltage regulator (02)"
    if name in ("RB", "CA", "ROUT"):
        return "Op-amp (03)"
    if name in ("RB2", "RB3", "RDAC"):
        return "DAC core (04)"
    if name.startswith("M") and n:
        k = int(n[:2]) if len(n) >= 2 else int(n)
        return "Voltage regulator (02)" if k <= 29 else ("Op-amp (03)" if k <= 49 else "DAC core (04)")
    return "other"


def rows(net, tag=None):
    out = []
    for l in net.splitlines():
        t = l.split()
        if not t or t[0][0] not in "MQRC" or t[0].startswith(("RL", "RLOAD")):
            continue
        kv = dict(re.findall(r"(\w+)=(\S+)", l))
        nm = t[0]
        if nm[0] == "M":
            out.append(dict(id=nm, model={"NWS": "nmos_NWS", "PHL": "pmos_PHL"}[t[5]], W=kv.get("w"), L=kv.get("l"), M=kv.get("m", "1"),
                            function=FUNC.get(f"{nm}@{tag}" if tag else nm, FUNC.get(nm, "")), block=block(nm) if not tag else "Characterisation (01)"))
        elif nm[0] == "Q":
            out.append(dict(id=nm.replace("Q§", ""), model="npn_npn (npn_EE4323)", W="", L="", M=f"area {t[6]}",
                            function=FUNC.get(f"{nm}@{tag}" if tag else nm, FUNC.get(nm, "")), block=block(nm) if not tag else "Characterisation (01)"))
        elif nm[0] in "RC":
            out.append(dict(id=nm, model="R_ndiff" if nm[0] == "R" else "C (ideal)", W="", L="", M=t[3].replace("µ", "u"),
                            function=FUNC.get(nm, ""), block=block(nm)))
    return out


